                    <h1>Ant-Massacre <br> <h3>Cooperative Wave-defense Game</h3></h1>
                    <img src="assets/Myror.png" width="275" height="auto"></img>
                    <p>
                        A 1-4 player cooperative game for PC where the players take on the roles as anteaters trying to eat as many ants as possible to prevent them from reaching their home.
                        This game was developed using Unity.
                        <br>
                        I worked on the gameplay scripting and handled the design of enemy behaviour and waves.
                        <br>
                        Ants will spawn from all sides of the game board and walk towards their nest in the middle of the screen.
                        The ants will spawn in waves, each wave being progressively more difficult and containing different types of ants.
                        The players will need to eat the ants by moving the anteater under their control so their tongue touches the ant. The anteaters can extend their tongues a short distance during a short period to reach ants further away. Every ant eaten will give the player points.
                        If 100 ants reaches their nest, the players lose.
                    </p>
