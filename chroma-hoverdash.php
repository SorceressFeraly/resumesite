            <h1>Post Mortem</h1>
                <h2 style ="text-align: left;">1. INTRODUCTION</h2>
                <p class = "paragraph">
                Under five weeks, our team of five artists, two programmers and two designers worked on making a racing game.
<br>
                None of us had undertaken a game project of this magnitude before.
<br>
                Despite many setbacks – sickness running rampant upon our programmers being among them – at the deadline we were still able to deliver a playable game.
<br>
                We were all beginners and there are several valuable lessons that we learned from this that we bring with us into the future.
</p>
<h2 style ="text-align: left;">2. WHAT WENT RIGHT</h2>
<h3 style ="text-align: left;">2.1 COMMUNICATION</h3>
<p class = "paragraph"> 
When we started out, we weren’t very good at using the tools that we had set up for planning. But the further we went into the project, people started to take more responsibility for updating their own plannings and make sure the tasks they were working on along with any dependencies were communicated early to the group.
<br>
No one in the group was afraid of questioning the work of others, and everyone were able to take criticism about their own work, which allowed everyone to improve.
<br><br>
Furthermore, the team was able to keep a good tone while communicating which contributed to a better work environment in the project.
<br>
We were able to stay focused on our work and even if it might have seemed quiet at times, maintain a friendly atmosphere – thankfully without the use of any Nerf guns!

<h3 style ="text-align: left;">2.2 NOT BEING AFRAID OF CUTTING STUFF</h3>
<p class = "paragraph">
As time went on, it became clear at times that certain features or assets just wouldn’t work with the direction the game was headed.
<br>
At those times, none in the team were afraid of cutting those parts of the game rather than trying to fit them in somehow, maybe not gladly, but understanding why – and the game was all the better for it. 
Three weeks into the project we decided to cut what had been the main feature of the game until then – the color trail.
<br><br>
While this changed the gameplay drastically, there is no doubt that what we were able to concentrate on delivering with this feature cut is much better than it would have been otherwise.
<br>
We tended to prepare in advance for these eventualities as well.
<br><br>
If we felt something was in a doubtful state, we’d figure out some fallback plan just in case, saving time.

<h3 style ="text-align: left;">2.3 EVERYONE HAD INPUT</h3>
<p class = "paragraph">
None on the team has been afraid of bringing up ideas of their own – and everyone’s input from the different disciplines improved the game.

<h3 style ="text-align: left;">2.4 GOOD WORK ENVIRONMENT</h3>
<p class = "paragraph">
We have been able to maintain a nice work environment where we have been keeping a good manner of speaking and showing understanding for each other’s’ work – even cross disciplines.

<h3 style ="text-align: left;">2.5 GOOD SPRINT PLANNING</h3>
<p class = "paragraph">
The way we distributed assignments meant that everyone had things to do, and it showed in the daily standups. Even if the meetings were too long initially, it got better over time.
</p> 
<h2 style ="text-align: left;">3. WHAT WENT WRONG</h2>
<h3 style ="text-align: left;">3.1 TERRIBLE COMMUNICATION AND PLANNING AT THE START</h3>
<p class = "paragraph">
Our naming conventions and HG Mercurial habits were pretty terrible at the beginning of the project. Within a few weeks we’d end up with several versions of the same stage with no one being really sure which was the latest one to run.
<br>
Improving on using all the functions of HG (backout in particular) should allow us to not make these mistakes again.
<br>
At the start of the project, we were far worse at just talking to each other.
<br>
Sure, it’s a new group, and everyone might not feel comfortable talking, but when important info about bug fixes does not reach the right people, or when someone is unsure what they are supposed to be doing, the communication has failed.
<br>
We all need to learn to talk to others earlier, and try to not let it take such a long time to build up a good communication.
<br>
If a person discovers that they have taken way too much work upon them, it’s important that they swallow their pride and share their workload with others of their discipline so that the task can get done in a good time. The person handing over the task need to be aware of that they haven’t done several small misses, that might be easier to fix for the original person.
<br><br>
More time spent in planning and pre-production might have made this easier – not necessarily in meetings, but perhaps while doing something fun?


<h3 style ="text-align: left;">3.2 INEFFECTIVE CONCEPT PHASE</h3>
<p class = "paragraph">
There was a needs for a greater common direction to go in. (More on this on the next point.)
<br>
A lot of the artists weren’t explicitly given instructions on what they should draw, so the styles on the concepts were all over the place.
<br><br>
During a meeting “Coruscant” (Star Wars city planet) was decided on for inspiration which made the direction a lot more apparent.
<br>
Since there were so many artists, appointing one as a “lead artist” who kept track of tasks and guided the process would probably have made the concepting easier.
<br><br>
Dedicating time to do research on the material to be presented would have been a good plan as well.


<h3 style ="text-align: left;">3.3 LOSS OF A COMMON VISION</h3>
<p class = "paragraph">
From the start, there was no clear vision of what this game was supposed to be.
<br><br>
For the next project a vision of the game must be nailed early and be apparent to everyone in the team, so both artists, programmers and designers know exactly what goal they’re working towards.
<br><br>
A suggestion of what we could do next time is to sit down day one, and look at everything the team realistically thinks that they can get into the game.
<br>
After that, remove everything but a third, and use that to figure out the core of the game.


<h3 style ="text-align: left;">3.4 BAD ROUTINES AND KNOWLEDGE ABOUT HG MERCURIAL</h3>
<p class = "paragraph">

We need to construct additional pushes.
<br>
Rather than pushing one completed change, we often made several commits as one single push. If something is done – commit it and push.
<br><br>
An idea that came up was to find a plugin that pings everyone when someone makes a push, or place tiny bells that each person press when pushing.
<br>
Additionally, the folders in the repositories should follow a good naming convention and be established early on.

<h3 style ="text-align: left;">3.5 BAD CODING STRUCTURE</h3>
<p class = "paragraph">
The programmers started at the wrong place, everything they completed last week they felt should have been ready in pre-production.
<br><br>
Instead of fixing the sinking ship, for several weeks they just kept adding band-aids until it all ended up a mess.
<br>
The prototyping should be given a higher focus, the steering didn’t feel just right until the final week. That should have worked with a blank box on a flat plane.
<br><br>
If you don’t know how to do something, feel free to test it, but make sure that you can clean it up afterwards.
</p>

